/**
 * Regenerate 0025_batch_journey_policies.sql from batch-journey-policies.json.
 *
 * Run from the database/ directory:  node build-batch-policies.mjs
 *
 * The JSON is the source of truth and the ids in it are literals, minted once.
 * Nothing here generates a UUID: a re-run that minted fresh ones would turn an
 * idempotent migration into twenty more customers every time it was applied.
 *
 * Every invariant the journey depends on is re-checked below on each run, and
 * a violation exits non-zero rather than writing a file that would quietly
 * strand a claim one step short of its refund.
 */
import fs from 'fs';

const rows = JSON.parse(fs.readFileSync('batch-journey-policies.json', 'utf8'));
const q = (v) => (v === null || v === undefined ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'");
const j = (v) => q(JSON.stringify(v)) + '::jsonb';

const active = rows.filter((r) => r.policy.status === 'active');
const expired = rows.filter((r) => r.policy.status === 'expired');

const money = (n) => n.toLocaleString('en-IN');
const payables = active.map((r) => r.journey.payable_after_deductible);
const minPayable = money(Math.min(...payables));
const maxPayable = money(Math.max(...payables));
const maxPremium = money(Math.max(...rows.map((r) => r.policy.premium_monthly)));
const maxAnnual = money(Math.max(...rows.map((r) => r.journey.renewal_premium_annual)));

const header = `-- ============================================
-- Migration 0025: twenty policies for the end-to-end journey batch
--
-- The seeded book of business is full of history, which is what makes lookups
-- worth demonstrating, and 0009 added three clean policies so a walkthrough
-- could begin at "file a claim". Neither is enough to run the journey twenty
-- times: the three demo policies collect a claim each on the first pass and
-- stop being clean, and every other policy already carries claims that trip
-- the near-duplicate check.
--
-- These twenty customers each hold exactly one policy and no claims. Fifteen
-- are active and are meant to be driven the whole way — file, adjudicate,
-- collect the deductible, approve, settle, refund. Five are lapsed and are
-- meant to be renewed first, so the renewal path is exercised by the same
-- batch rather than being demonstrated separately.
--
-- Re-running this file restores the twenty rows and does not delete claims
-- filed against them.
--
-- Generated by database/build-batch-policies.mjs — do not edit by hand.
--
-- ## Why these numbers and not others
--
-- Three ceilings in the code decide whether a claim on one of these policies
-- can actually reach a refund, and every row below sits inside all three.
--
--   50,000   settlement-service.ts  DEFAULT_SETTLEMENT_AUTO_APPROVE_LIMIT
--            min(claimed, coverage) - deductible must not exceed it, or
--            settle-claim refuses with 'above_auto_approve_limit' and the
--            journey stops one step short of the money. The suggested claim
--            amounts in the comments below leave between ${minPayable} and
--            ${maxPayable} payable on the fifteen active policies.
--
--  100,000   deductible-service.ts  DEFAULT_DEDUCTIBLE_MAX_LINK_AMOUNT
--            the largest deductible the agent may put behind a payment link.
--            These carry a 1,000-2,000 motor excess and a 5,000-10,000 excess
--            on home and health, which is what an Indian policy of each kind
--            actually carries.
--
--  200,000   renewal-service.ts     DEFAULT_RENEWAL_MAX_LINK_AMOUNT
--            premium_monthly x 12 must not exceed it, or offer-renewal
--            refuses with 'above_link_limit'. The dearest here is ${maxPremium}
--            a month, so ${maxAnnual} a year.
--
-- ## Why the five are 'expired' and not 'cancelled'
--
-- renewal-service.ts Gate 2 offers a link only for a policy whose status reads
-- exactly 'expired'. 'cancelled' is refused permanently and deliberately — a
-- cancelled policy was terminated by a decision, and no amount of money paid
-- to a voice agent may put it back in force. Their terms also ended in the
-- past, so a claim filed against one BEFORE it is renewed is denied by
-- 'policy_in_force_on_incident_date' in adjudication-rules.ts, in code, before
-- any model is called. That denial is a passing test, not a failure: it is the
-- refusal the renewal offer then answers.
--
-- ## No new policy_type is introduced
--
-- adjudication-rules.ts holds a coverage schedule for auto, home, health and
-- life only. A policy of any other type reaches 'claim_type_covered' with no
-- schedule to check against and vetoes to 'escalate' before the model runs,
-- which would stop all twenty journeys at adjudication. Life is scheduled but
-- unused here: its covered claim types are death and terminal_illness, and
-- driving one of those through a deductible payment and a refund is not a
-- journey worth demonstrating.
-- ============================================

-- --- Customers --------------------------------------------------------------

INSERT INTO customers (id, full_name, email, phone, date_of_birth, address) VALUES
`;

const customerValues = rows
  .map((r) => {
    const c = r.customer;
    return `  (${q(c.id)}, ${q(c.full_name)}, ${q(c.email)}, ${q(c.phone)}, ${q(c.date_of_birth)}, ${q(c.address)})`;
  })
  .join(',\n');

const policyLine = (r) => {
  const p = r.policy;
  const jn = r.journey;
  const comment =
    `  -- ${p.policy_number}  ${r.customer.full_name} — ${jn.claim_type} claim of ${money(jn.suggested_claim_amount)} ` +
    `leaves ${money(jn.payable_after_deductible)} payable` +
    (p.status === 'expired' ? `; renew at ${money(jn.renewal_premium_annual)} first` : '');
  const values =
    `  (${q(p.id)}, ${q(p.policy_number)}, ${q(p.customer_id)}, ${q(p.policy_type)}, ${q(p.provider)}, ` +
    `${p.coverage_amount}, ${p.deductible}, ${p.premium_monthly}, ${q(p.start_date)}, ${q(p.end_date)}, ` +
    `${q(p.status)}, ${j(p.coverage_details)})`;
  return comment + '\n' + values;
};

const sql =
  header +
  customerValues +
  '\nON CONFLICT (id) DO NOTHING;\n\n' +
  '-- --- The fifteen active policies: file a claim straight away ---------------\n\n' +
  'INSERT INTO policies (id, policy_number, customer_id, policy_type, provider, coverage_amount, deductible, premium_monthly, start_date, end_date, status, coverage_details) VALUES\n' +
  active.map(policyLine).join(',\n') +
  '\nON CONFLICT (id) DO NOTHING;\n\n' +
  '-- --- The five lapsed policies: renew, then file ----------------------------\n' +
  '--\n' +
  '-- A claim filed against one of these before renewal is denied on the date,\n' +
  '-- by arithmetic, with no model involved. Renew it and the reactivated term\n' +
  '-- starts today, so file with an incident date on or after the renewal.\n\n' +
  'INSERT INTO policies (id, policy_number, customer_id, policy_type, provider, coverage_amount, deductible, premium_monthly, start_date, end_date, status, coverage_details) VALUES\n' +
  expired.map(policyLine).join(',\n') +
  '\nON CONFLICT (id) DO NOTHING;\n\n' +
  `-- --- Resetting between runs -------------------------------------------------
--
-- Clears claims filed against the twenty, returning them to a clean slate for
-- another pass. Deliberately commented out: running it by accident during a
-- recorded walkthrough would delete the evidence of the walkthrough.
--
--   DELETE FROM claims WHERE policy_id IN (
--     SELECT id FROM policies
--     WHERE policy_number BETWEEN 'POL-2026-300001' AND 'POL-2026-300020'
--   );
--
-- Putting the five lapsed ones back after a renewal has reactivated them:
--
--   UPDATE policies SET status = 'expired', start_date = t.start_date, end_date = t.end_date
--   FROM (VALUES
${expired
  .map((r) => `--     ('${r.policy.policy_number}', DATE '${r.policy.start_date}', DATE '${r.policy.end_date}')`)
  .join(',\n')}
--   ) AS t(policy_number, start_date, end_date)
--   WHERE policies.policy_number = t.policy_number;
`;

// --- The invariants, re-checked on every regeneration -----------------------
//
// Each of these corresponds to a gate in the code that would refuse a step of
// the journey. They are asserted here rather than discovered halfway through a
// recorded walkthrough.

const problems = [];
const note = (label, bad) => {
  if (bad.length) problems.push(label + ': ' + bad.map((r) => r.policy.policy_number).join(', '));
};

note(
  'payable is outside (0, 50000] and settle-claim would refuse it',
  rows.filter((r) => r.journey.payable_after_deductible <= 0 || r.journey.payable_after_deductible > 50000)
);
note(
  'claimed more than the coverage, which escalates at claimed_amount_within_coverage',
  rows.filter((r) => r.journey.suggested_claim_amount > r.policy.coverage_amount)
);
note(
  'annual premium is above the 200000 renewal link ceiling',
  rows.filter((r) => r.journey.renewal_premium_annual > 200000)
);
note(
  'deductible is above the 100000 link cap',
  rows.filter((r) => r.policy.deductible > 100000)
);
note(
  'is meant to be lapsed but its term has not ended',
  expired.filter((r) => r.policy.end_date >= r.policy.start_date && new Date(r.policy.end_date) >= new Date())
);
note(
  'is meant to be active but its status does not read active',
  active.filter((r) => r.policy.status !== 'active')
);
note(
  "is meant to be renewable but its status does not read exactly 'expired'",
  expired.filter((r) => r.policy.status !== 'expired')
);

const scheduled = new Set(['auto', 'home', 'health', 'life']);
note(
  'has a policy_type adjudication-rules.ts holds no coverage schedule for',
  rows.filter((r) => !scheduled.has(r.policy.policy_type))
);

const seenNumbers = new Set();
const seenPhones = new Set();
for (const r of rows) {
  if (seenNumbers.has(r.policy.policy_number)) problems.push('duplicate policy number: ' + r.policy.policy_number);
  if (seenPhones.has(r.customer.phone)) problems.push('duplicate phone: ' + r.customer.phone);
  seenNumbers.add(r.policy.policy_number);
  seenPhones.add(r.customer.phone);
}

if (problems.length) {
  console.error('Refusing to write the migration. ' + problems.length + ' invariant(s) violated:');
  for (const p of problems) console.error('  - ' + p);
  process.exit(1);
}

fs.writeFileSync('0025_batch_journey_policies.sql', sql);
console.log('wrote 0025_batch_journey_policies.sql (' + sql.split('\n').length + ' lines)');
