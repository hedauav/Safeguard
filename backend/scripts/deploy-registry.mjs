/**
 * Compile and deploy ClaimRegistry to Base Sepolia.
 *
 * Uses solc directly so Foundry is not required. The compiled ABI is written
 * to src/abis/ClaimRegistry.json so the backend and the deployed contract can
 * never drift apart.
 *
 *   npm run deploy:registry
 *
 * Reads AGENT_PRIVATE_KEY and BASE_SEPOLIA_RPC_URL from backend/.env.
 * Prints the deployed address to set as CLAIM_REGISTRY_ADDRESS.
 */
import 'dotenv/config';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { createPublicClient, createWalletClient, http, formatEther } from 'viem';
import { baseSepolia } from 'viem/chains';
import { privateKeyToAccount } from 'viem/accounts';

const require = createRequire(import.meta.url);
const solc = require('solc');

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const contractPath = join(root, '..', 'contracts', 'src', 'ClaimRegistry.sol');

const RPC = process.env.BASE_SEPOLIA_RPC_URL || 'https://sepolia.base.org';
const KEY = process.env.AGENT_PRIVATE_KEY;

if (!KEY) {
  console.error('AGENT_PRIVATE_KEY is not set in backend/.env');
  process.exit(1);
}

// --- Compile ----------------------------------------------------------------

console.log('Compiling ClaimRegistry.sol ...');

const source = readFileSync(contractPath, 'utf8');
const input = {
  language: 'Solidity',
  sources: { 'ClaimRegistry.sol': { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));

const errors = (output.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}
for (const w of (output.errors ?? []).filter((e) => e.severity === 'warning')) {
  console.log('  warning: ' + w.message.trim().split('\n')[0]);
}

const artifact = output.contracts['ClaimRegistry.sol'].ClaimRegistry;
const abi = artifact.abi;
const bytecode = '0x' + artifact.evm.bytecode.object;

console.log(`  compiled — ${abi.length} ABI entries, ${(bytecode.length - 2) / 2} bytes\n`);

// Keep the backend's ABI in lockstep with what is actually deployed.
writeFileSync(
  join(root, 'src', 'abis', 'ClaimRegistry.json'),
  JSON.stringify(
    {
      _comment:
        'Generated by scripts/deploy-registry.mjs from contracts/src/ClaimRegistry.sol. Do not edit by hand.',
      abi,
    },
    null,
    2
  ) + '\n'
);
console.log('  wrote src/abis/ClaimRegistry.json\n');

// --- Deploy -----------------------------------------------------------------

const account = privateKeyToAccount(KEY);
const publicClient = createPublicClient({ chain: baseSepolia, transport: http(RPC) });
const walletClient = createWalletClient({ account, chain: baseSepolia, transport: http(RPC) });

console.log(`Deployer : ${account.address}`);

const balance = await publicClient.getBalance({ address: account.address });
console.log(`Balance  : ${formatEther(balance)} ETH`);

if (balance === 0n) {
  console.error('\nThis wallet has no Base Sepolia ETH. Fund it first:');
  console.error('  https://www.alchemy.com/faucets/base-sepolia');
  process.exit(1);
}

console.log('\nDeploying ...');
const hash = await walletClient.deployContract({ abi, bytecode, args: [] });
console.log(`  tx: ${hash}`);

const receipt = await publicClient.waitForTransactionReceipt({ hash });

if (receipt.status !== 'success' || !receipt.contractAddress) {
  console.error('Deployment failed:', receipt.status);
  process.exit(1);
}

// Confirm the contract really is live and owned by the deployer.
const owner = await publicClient.readContract({
  address: receipt.contractAddress,
  abi,
  functionName: 'owner',
});

console.log('\nDeployed successfully.');
console.log(`  address   : ${receipt.contractAddress}`);
console.log(`  owner     : ${owner}`);
console.log(`  gas used  : ${receipt.gasUsed}`);
console.log(`  explorer  : https://sepolia.basescan.org/address/${receipt.contractAddress}`);
console.log(`\nSet this on Railway:\n  CLAIM_REGISTRY_ADDRESS=${receipt.contractAddress}`);
